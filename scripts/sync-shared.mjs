// Copies the website chat's pure modules (no DOM) into src/shared, so the app
// chat and the website chat read the same API shapes, guided conversation and
// copy. Run after changing them in the website chat:
//
//   node scripts/sync-shared.mjs path/to/the/website/chat/components
//
// Files are copied verbatim with a header; never edit them here.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

if (!process.argv[2]) throw new Error("Usage: node scripts/sync-shared.mjs path/to/the/website/chat/components");
const source = resolve(process.argv[2]);
const target = resolve("src/shared");
const HEADER =
  "// Shared with Achille's website chat, so the app and the website behave\n" +
  "// alike. Generated by scripts/sync-shared.mjs: do not edit it here.\n\n";

const FILES = [
  "attachments.ts",
  "awaiting-reply.ts",
  "conditions.ts",
  "conversation-strings.ts",
  "conversations.ts",
  "flow-api.ts",
  "flow-engine.ts",
  "flow-strings.ts",
  "human-mode.ts",
  "privacy-notice.ts",
  "readable-color.ts",
  "ui-language.ts",
  "use-conversation-flow.ts",
];

for (const file of FILES) {
  const body = readFileSync(join(source, file), "utf8");
  writeFileSync(join(target, file), HEADER + body);
  console.log(`synced ${file}`);
}

// The chat's built-in copy lives inside the widget's main component: its
// UI_STRINGS object is lifted out as is.
const chat = readFileSync(join(source, "widget-chat.tsx"), "utf8");
const block = chat.match(/\nconst UI_STRINGS = (\{[\s\S]*?\n\});\n/);
if (!block) throw new Error("UI_STRINGS not found in widget-chat.tsx");
writeFileSync(
  join(target, "ui-strings.ts"),
  HEADER +
    `export const UI_STRINGS = ${block[1]};\n\n` +
    `export type UiStrings = (typeof UI_STRINGS)["fr"];\n\n` +
    `export const UI_LANGUAGES = Object.keys(UI_STRINGS) as (keyof typeof UI_STRINGS)[];\n\n` +
    `export function uiStringsFor(lang: string): UiStrings {\n` +
    `  return (UI_STRINGS as Record<string, UiStrings>)[lang] ?? UI_STRINGS.en;\n}\n`
);
console.log("synced ui-strings.ts (from widget-chat.tsx)");
